test_restart_now_when_idle_or_later() {
  DC_RUNNING=1; _stubs
  local a out; a="$(_dir app)"
  terminal_ready() { return 0; }
  # --yes: now — the sandbox recreated with its new mounts, the code container untouched
  project_add "$a" 2>/dev/null || return 1
  assert_contains "$(cat "$TMP/dc")" "dc up -d --no-deps --wait terminal"
  assert_not_contains "$(cat "$TMP/dc")" "up -d --no-deps --wait code"
  : > "$TMP/dc"
  project_mode app ro --later 2>/dev/null || return 1
  assert_not_contains "$(cat "$TMP/dc")" "up -d"
  # when idle: waits while a turn runs, at most PROJECTS_IDLE_MAX_S; still busy then: not restarted, said
  projects_busy() { echo 2; }
  sleep() { :; }
  PROJECTS_IDLE_MAX_S=30 PROJECTS_IDLE_POLL_S=10
  out="$(project_mode app rw --when-idle 2>&1)" || return 1
  assert_contains "$out" "waiting until no Code session has a turn running (2 now; at most 0 minutes)"
  assert_contains "$out" "the sandbox was not restarted — ./stack project apply restarts it"
  assert_not_contains "$(cat "$TMP/dc")" "up -d --no-deps --wait terminal"
  assert_eq "$(_rec app | cut -f3)" rw   # (the change itself is made)
  # idle at once: restarted
  projects_busy() { echo 0; }
  project_mode app ro --when-idle 2>/dev/null || return 1
  assert_contains "$(cat "$TMP/dc")" "dc up -d --no-deps --wait terminal"
}

