    rmdir "/tmp/bn-pj-$$"
  fi
  # characters Docker or compose would misread, or the generated files could not hold
  for n in 'a:b' 'a,b' 'a$b' 'a"b' "a'b" 'a`b' 'a\b'; do
    mkdir -p "$TMP/f/$n"
    if project_check "$TMP/f/$n" >/dev/null 2>&1; then echo "accepted $n" >&2; return 1; fi
  done
  mkdir -p "$TMP/f/a"$'\t'"b"
  if project_check "$TMP/f/a"$'\t'"b" >/dev/null 2>&1; then echo "accepted a tab" >&2; return 1; fi
  # a space is fine
  mkdir -p "$TMP/f/with space"
  project_check "$TMP/f/with space" >/dev/null || return 1
}

