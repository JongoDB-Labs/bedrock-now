_stubs() {
  export ASSUME_YES=1 HOME="$TMP/home"
  mkdir -p "$HOME" "$TMP/f"
  stack_lock() { :; }
  stack_unlock() { :; }
  run_phase() { shift 2; "$@"; }
  DC_RUNNING="${DC_RUNNING:-}"; DC_FAIL_UP="${DC_FAIL_UP:-}"
  dc() {
    echo "dc $*" >> "$TMP/dc"
    case "$*" in
      "ps -q --status running "*) [ -z "$DC_RUNNING" ] || echo abc123 ;;
      "up -d --no-deps --wait terminal") [ -z "$DC_FAIL_UP" ] || { echo "Error: mounts denied: $DC_FAIL_UP" ; return 1; } ;;
    esac
    return 0
  }
  docker() { echo "docker $*" >> "$TMP/docker"; return 0; }
